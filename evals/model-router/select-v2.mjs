// After the v2 calibration run (every candidate once on all 8 arms), sort
// candidates by how many arms failed them and pick the final set:
//   easy = no arm failed, medium = 1-2 failed, hard = 3+ failed.
// Picks round-robin across families so no one generator dominates a bucket.
// Writes tasks-v2-final.mjs, which EVAL_SET=v2 then uses for repeat rounds.
//   EVAL_SET=v2 node select-v2.mjs
import { writeFileSync } from 'node:fs';
import { POOL } from './tasks-v2.mjs';
import { grade } from './graders.mjs';
import { ARMS, readRaw } from './run-models.mjs';

const TARGET = { easy: 100, medium: 50, hard: 25 };
const byId = Object.fromEntries(POOL.map(t => [t.id, t]));
const fails = {};
for (const r of readRaw()) {
  if (r.rep !== 0 || !byId[r.task]) continue;
  const pass = r.finish_reason === 'length' && !r.text?.trim() ? false : grade(byId[r.task], r.text ?? '').pass;
  (fails[r.task] ||= {})[r.arm] = !pass;
}
const bucketOf = id => { const f = fails[id]; if (!f || ARMS.some(a => !(a in f))) return null; const n = Object.values(f).filter(Boolean).length; return n === 0 ? 'easy' : n <= 2 ? 'medium' : 'hard'; };

const buckets = { easy: [], medium: [], hard: [] };
for (const t of POOL) { const b = bucketOf(t.id); if (b) buckets[b].push(t); }
const roundRobin = (tasks, n) => {
  const fam = {}; for (const t of tasks) (fam[t.family] ||= []).push(t);
  const lists = Object.values(fam), out = [];
  while (out.length < n && lists.some(l => l.length)) for (const l of lists) if (l.length && out.length < n) out.push(l.shift());
  return out;
};
const chosen = Object.fromEntries(Object.entries(TARGET).map(([b, n]) => [b, roundRobin(buckets[b], n)]));
const final = Object.entries(chosen).flatMap(([b, ts]) => ts.map(t => ({ ...t, difficulty: b, bucket: b, failed_arms: Object.values(fails[t.id]).filter(Boolean).length })));

writeFileSync(new URL('./tasks-v2-final.mjs', import.meta.url),
  `// Generated by select-v2.mjs from the calibration run. Do not edit by hand.\nimport { POOL } from './tasks-v2.mjs';\nconst PICK = ${JSON.stringify(Object.fromEntries(final.map(t => [t.id, { bucket: t.bucket, failed_arms: t.failed_arms }])), null, 0)};\nexport const TASKS_OR_POOL = POOL.filter(t => PICK[t.id]).map(t => ({ ...t, difficulty: PICK[t.id].bucket, bucket: PICK[t.id].bucket, failed_arms: PICK[t.id].failed_arms }));\n`);

const calibrated = POOL.filter(t => bucketOf(t.id)).length;
console.log(`calibrated ${calibrated} of ${POOL.length} candidates`);
for (const b of Object.keys(TARGET)) {
  const fam = {}; for (const t of chosen[b]) fam[t.family] = (fam[t.family] || 0) + 1;
  console.log(`${b.padEnd(6)} available ${String(buckets[b].length).padStart(3)}, picked ${String(chosen[b].length).padStart(3)} of ${TARGET[b]}  ${JSON.stringify(fam)}`);
}
console.log('wrote tasks-v2-final.mjs');
